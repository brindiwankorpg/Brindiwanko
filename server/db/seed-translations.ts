/**
 * Rewrites the text of a seed value in the language chosen for the content. French is the
 * language the demo is written in, so it is returned as it is; for English every string is
 * looked up in `EN_TEXT` (plain objects and arrays are walked, other values are kept).
 * @param value - Seed record, settings value or map data.
 * @param language - Language of the content.
 */
export function localize<T>(value: T, language: Locale): T {
  if (language === 'fr') return value;
  const walk = (v: unknown): unknown => {
    if (typeof v === 'string') return EN_TEXT.get(v) ?? v;
    if (Array.isArray(v)) return v.map(walk);
    if (v !== null && typeof v === 'object' && Object.getPrototypeOf(v) === Object.prototype) {
      return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)]));
    }
    return v;
  };
  return walk(value) as T;
}

/** A demo map with its in-game name and its events (dialogues, notes) in the chosen language. */
export function localizeMap<T extends { displayName: string; events: unknown }>(map: T, language: Locale): T {
  if (language === 'fr') return map;
  return { ...map, displayName: localize(map.displayName, language), events: localize(map.events, language) };
}
